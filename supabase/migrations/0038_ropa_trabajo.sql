-- Entregas de ropa de trabajo: pantalón, camisa y buzo, con talle
-- según el tipo. Solo administración (admin/subadmin).
--
-- Cómo aplicarlo: abrí Supabase → SQL Editor, pegá este archivo
-- completo y ejecutalo.
-- ============================================================

create table if not exists public.ropa_entregas (
  id bigint generated by default as identity primary key,
  fecha timestamptz not null default now(),
  categoria text not null check (categoria in ('Pantalon', 'Camisa', 'Buzo')),
  talle text not null,
  destinatario text not null,
  cantidad numeric not null default 1,
  observaciones text,
  usuario_email text,
  created_at timestamptz not null default now()
);

create index if not exists ropa_entregas_destinatario_idx on public.ropa_entregas (destinatario);
create index if not exists ropa_entregas_categoria_idx on public.ropa_entregas (categoria);

alter table public.ropa_entregas enable row level security;

drop policy if exists "ropa_entregas_gestion_all" on public.ropa_entregas;
create policy "ropa_entregas_gestion_all" on public.ropa_entregas
  for all to authenticated
  using (public.es_gestion())
  with check (public.es_gestion());
