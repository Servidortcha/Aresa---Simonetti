-- ============================================================
-- 0041_pagos_proveedores.sql
-- Módulo de pagos a proveedores:
--   * facturas_proveedor: factura cargada con su archivo adjunto.
--   * pagos_factura: pagos imputados a una factura, cada uno con
--     su comprobante obligatorio. Permite pagos parciales.
--   * Bucket privado "facturas-pagos" para facturas y comprobantes.
--
-- Reglas:
--   - La suma de pagos no puede superar el importe de la factura.
--   - El importe de una factura no puede quedar por debajo de lo
--     que ya tiene pagado.
--   - Solo admin, subadmin y el rol "compras" acceden.
--
-- Cómo aplicarlo: abrí Supabase → SQL Editor, pegá este archivo
-- completo y ejecutalo.
-- ============================================================

create table if not exists public.facturas_proveedor (
  id bigint generated by default as identity primary key,
  numero text not null,
  proveedor text not null,
  fecha date not null default current_date,
  vencimiento date,
  importe numeric(14,2) not null check (importe > 0),
  moneda text not null default 'ARS' check (moneda in ('ARS', 'USD')),
  categoria text,
  observaciones text,
  archivo_path text not null,
  archivo_nombre text,
  usuario_email text,
  created_at timestamptz not null default now()
);

create table if not exists public.pagos_factura (
  id bigint generated by default as identity primary key,
  factura_id bigint not null references public.facturas_proveedor(id) on delete cascade,
  fecha date not null default current_date,
  importe numeric(14,2) not null check (importe > 0),
  medio_pago text not null default 'Transferencia'
    check (medio_pago in ('Transferencia', 'Cheque', 'Efectivo', 'Tarjeta', 'Otro')),
  referencia text,
  observaciones text,
  comprobante_path text not null,
  comprobante_nombre text,
  usuario_email text,
  created_at timestamptz not null default now()
);

create index if not exists facturas_proveedor_fecha_idx on public.facturas_proveedor (fecha desc);
create index if not exists facturas_proveedor_proveedor_idx on public.facturas_proveedor (proveedor);
create index if not exists pagos_factura_factura_idx on public.pagos_factura (factura_id);
create index if not exists pagos_factura_fecha_idx on public.pagos_factura (fecha desc);

-- ------------------------------------------------------------
-- Validaciones de saldo
-- ------------------------------------------------------------
create or replace function public.validar_pago_factura()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_importe numeric(14,2);
  v_pagado numeric(14,2);
begin
  select importe into v_importe
  from public.facturas_proveedor
  where id = NEW.factura_id;

  if not found then
    raise exception 'La factura no existe.';
  end if;

  select coalesce(sum(importe), 0) into v_pagado
  from public.pagos_factura
  where factura_id = NEW.factura_id
    and (TG_OP = 'INSERT' or id <> NEW.id);

  if v_pagado + NEW.importe > v_importe + 0.005 then
    raise exception 'El pago supera el saldo pendiente de la factura (saldo: %).',
      (v_importe - v_pagado);
  end if;

  return NEW;
end;
$$;

drop trigger if exists trg_validar_pago_factura on public.pagos_factura;
create trigger trg_validar_pago_factura
  before insert or update on public.pagos_factura
  for each row execute function public.validar_pago_factura();

create or replace function public.validar_importe_factura()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pagado numeric(14,2);
begin
  select coalesce(sum(importe), 0) into v_pagado
  from public.pagos_factura
  where factura_id = NEW.id;

  if v_pagado > NEW.importe + 0.005 then
    raise exception 'El importe de la factura no puede ser menor a lo ya pagado (%).',
      v_pagado;
  end if;

  return NEW;
end;
$$;

drop trigger if exists trg_validar_importe_factura on public.facturas_proveedor;
create trigger trg_validar_importe_factura
  before update of importe on public.facturas_proveedor
  for each row execute function public.validar_importe_factura();

-- ------------------------------------------------------------
-- RLS
-- ------------------------------------------------------------
alter table public.facturas_proveedor enable row level security;
alter table public.pagos_factura enable row level security;

drop policy if exists "facturas_proveedor_gestion_all" on public.facturas_proveedor;
create policy "facturas_proveedor_gestion_all" on public.facturas_proveedor
  for all to authenticated
  using (public.es_gestion() or public.es_compras())
  with check (public.es_gestion() or public.es_compras());

drop policy if exists "pagos_factura_gestion_all" on public.pagos_factura;
create policy "pagos_factura_gestion_all" on public.pagos_factura
  for all to authenticated
  using (public.es_gestion() or public.es_compras())
  with check (public.es_gestion() or public.es_compras());

-- ------------------------------------------------------------
-- Storage privado: facturas y comprobantes
-- ------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('facturas-pagos', 'facturas-pagos', false)
on conflict (id) do update set public = false;

drop policy if exists "facturas_pagos_storage_select" on storage.objects;
create policy "facturas_pagos_storage_select" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'facturas-pagos'
    and (public.es_gestion() or public.es_compras())
  );

drop policy if exists "facturas_pagos_storage_insert" on storage.objects;
create policy "facturas_pagos_storage_insert" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'facturas-pagos'
    and (public.es_gestion() or public.es_compras())
  );

drop policy if exists "facturas_pagos_storage_update" on storage.objects;
create policy "facturas_pagos_storage_update" on storage.objects
  for update to authenticated
  using (
    bucket_id = 'facturas-pagos'
    and (public.es_gestion() or public.es_compras())
  )
  with check (
    bucket_id = 'facturas-pagos'
    and (public.es_gestion() or public.es_compras())
  );

drop policy if exists "facturas_pagos_storage_delete" on storage.objects;
create policy "facturas_pagos_storage_delete" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'facturas-pagos'
    and (public.es_gestion() or public.es_compras())
  );
